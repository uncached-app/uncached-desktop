#!/usr/bin/env node
/**
 * Builds a workspace worth stressing the app against.
 *
 * Not a pile of empty folders. Every screen in Uncached reads something
 * specific off the disk — a verdict reads git, a family reads the directory
 * above a project, the duplicate report reads package manifests inside
 * `node_modules`, the map reads all three at once — so a fixture that skips any
 * of them tests the layout and nothing else. This makes real repositories with
 * real remotes, real manifests, and overlapping installs.
 *
 * Weight comes from sparse files. The scanner sums `metadata.len()`, which is
 * the logical size, so a hundred gigabytes of fixture costs a few megabytes of
 * actual disk and writes in seconds. The figures on screen are honest about
 * what the app would report; they are not honest about what the disk holds, and
 * that is the trade being made.
 *
 *   node scripts/bench-workspace.mjs                 # build it
 *   node scripts/bench-workspace.mjs --projects 120  # a bigger one
 *   node scripts/bench-workspace.mjs --clean         # remove it
 *
 * `--clean` refuses to touch a directory this did not create, and so does the
 * build: the marker file is the only thing that makes a path fair game.
 */

import { execFileSync } from "node:child_process";
import { closeSync, existsSync, ftruncateSync, mkdirSync, openSync, rmSync, symlinkSync, utimesSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const MARKER = ".uncached-bench";
const MB = 1024 * 1024;
const DAY = 24 * 60 * 60 * 1000;

const options = parseArguments(process.argv.slice(2));
const root = options.root ?? join(homedir(), "Documents", "Workspace", "uncached-bench");

/** Packages installed across projects, so the duplicate report has real work. */
const CATALOGUE = [
  ["react", "18.3.1", 6],
  ["typescript", "5.8.2", 22],
  ["esbuild", "0.24.0", 19],
  ["lodash", "4.17.21", 5],
  ["zod", "3.23.8", 2],
  ["vite", "7.0.1", 14],
  ["@types/node", "22.9.0", 9],
  ["rollup", "4.28.0", 11],
  ["prettier", "3.4.2", 8],
  ["eslint", "9.16.0", 13],
];

/** Directories that hold more than one project, which is what a family is. */
const FAMILIES = [
  { name: "acme-platform", declare: "pnpm", members: ["web", "api", "admin", "ui-kit"] },
  { name: "rust-tools", declare: "cargo", members: ["cli", "core", "macros"] },
  { name: "services", declare: null, members: ["auth", "billing", "search", "notify"] },
  { name: "go-stack", declare: "go", members: ["gateway", "worker"] },
  { name: "labs", declare: "npm", members: ["proto-a", "proto-b"] },
];

if (options.clean) {
  clean();
} else {
  build();
}

function build() {
  if (existsSync(root) && !existsSync(join(root, MARKER))) {
    fail(`${root} exists and was not created by this script. Refusing to write into it.`);
  }

  const started = Date.now();
  mkdirSync(root, { recursive: true });
  writeFileSync(join(root, MARKER), "Generated by scripts/bench-workspace.mjs. Safe to delete.\n");

  const origins = join(root, ".origins");
  mkdirSync(origins, { recursive: true });

  const random = seeded(options.seed);
  const made = [];

  for (const family of FAMILIES) {
    const directory = join(root, family.name);
    mkdirSync(directory, { recursive: true });
    declareWorkspace(directory, family);
    for (const member of family.members) {
      made.push(makeProject(join(directory, member), { origins, random }));
    }
  }

  // Two checkouts of one repository, which is the clone edge on the map and the
  // clones filter in the list.
  const shared = makeOrigin(origins, "payments");
  // The first checkout gives the repository a commit; the second is a clone of
  // something, which is what makes them a pair rather than two empty folders.
  const first = join(root, "payments");
  git(root, ["clone", "-q", shared, first]);
  git(first, ["config", "user.email", "bench@uncached.app"]);
  git(first, ["config", "user.name", "Bench"]);
  writeSource(first, "node");
  git(first, ["add", "-A"]);
  commit(first, "first", 12);
  git(first, ["push", "-q", "-u", "origin", "main"]);
  fillProject(first, { random, kind: "node" });
  made.push(first);

  const second = join(root, "payments-hotfix");
  git(root, ["clone", "-q", shared, second]);
  fillProject(second, { random, kind: "node" });
  made.push(second);

  // Both ends of the pair take the same URL, which is what makes them one
  // repository rather than two projects that happen to look alike.
  offMachine(first, "payments");
  offMachine(second, "payments");

  for (let at = 0; at < options.projects; at += 1) {
    made.push(makeProject(join(root, `solo-${String(at + 1).padStart(3, "0")}`), { origins, random }));
  }

  // Build directories nothing owns: the leftovers of a project that was
  // deleted, which Insights reports and refuses to clean.
  const orphans = join(root, "leftovers");
  mkdirSync(orphans, { recursive: true });
  for (const name of ["old-site", "scratch-api"]) {
    const modules = join(orphans, name, "node_modules");
    mkdirSync(modules, { recursive: true });
    sparse(join(modules, "bulk.bin"), 240 * MB);
  }
  const abandoned = join(orphans, "dead-tool", "target");
  mkdirSync(abandoned, { recursive: true });
  writeFileSync(join(abandoned, "CACHEDIR.TAG"), "Signature: 8a477f597d28d172789f06886806bc55\n");
  sparse(join(abandoned, "debug.bin"), 900 * MB);

  report(made, Date.now() - started);
}

/**
 * One project: a repository with a remote, a manifest, and the artifacts its
 * ecosystem leaves behind.
 *
 * The variation is the point. Every project alike gives one verdict, one age
 * and one weight, and a screen that groups by any of those has nothing to show.
 */
function makeProject(path, { origins, random }) {
  const name = path.split("/").pop();
  const kind = pick(random, ["node", "node", "node", "rust", "python", "go"]);
  const age = Math.floor(random() * 400);

  mkdirSync(path, { recursive: true });
  const origin = makeOrigin(origins, name);
  git(path, ["init", "-q", "--initial-branch=main"]);
  git(path, ["config", "user.email", "bench@uncached.app"]);
  git(path, ["config", "user.name", "Bench"]);
  git(path, ["remote", "add", "origin", origin]);

  // Source first, committed, pushed — then the artifacts, which git never sees.
  // Ordering rather than trusting `.gitignore` alone: a sparse file added by
  // accident is read in full and written into the object store, which is how a
  // fixture meant to cost nothing fills a disk.
  writeSource(path, kind);
  git(path, ["add", "-A"]);
  commit(path, "first", age + 30);
  git(path, ["push", "-q", "-u", "origin", "main"]);
  offMachine(path, name);

  fillProject(path, { random, kind });

  // Four shapes of recoverability, which is what decides a verdict. Only the
  // first is `safe`; the rest are the ones automation must never touch.
  const shape = random();
  if (shape < 0.2) {
    writeFileSync(join(path, "NOTES.md"), "Work that exists only here.\n");
    git(path, ["add", "-A"]);
    commit(path, "not pushed anywhere", age);
  } else if (shape < 0.3) {
    writeFileSync(join(path, "wip.txt"), "half a thought\n");
    git(path, ["stash", "-q", "-u"]);
  } else if (shape < 0.4) {
    git(path, ["checkout", "-q", "-b", "experiment"]);
    writeFileSync(join(path, "experiment.txt"), "no upstream for this one\n");
    git(path, ["add", "-A"]);
    commit(path, "on a branch with no remote", age);
  } else if (shape < 0.5) {
    writeFileSync(join(path, "untracked.txt"), "never committed\n");
  }

  return path;
}

/** The files a repository actually tracks: manifest, lockfile, readme, ignores. */
function writeSource(path, kind) {
  const name = path.split("/").pop();
  writeFileSync(join(path, "README.md"), `# ${name}\n\nGenerated fixture.\n`);
  writeFileSync(
    join(path, ".gitignore"),
    "node_modules/\ntarget/\n.next/\n.turbo/\ndist/\nbuild/\n.venv/\n__pycache__/\n.pnpm-store/\n",
  );

  if (kind === "node") {
    writeFileSync(
      join(path, "package.json"),
      `${JSON.stringify({ name, version: "1.0.0", private: true }, null, 2)}\n`,
    );
    writeFileSync(join(path, "package-lock.json"), '{"lockfileVersion":3}\n');
  } else if (kind === "rust") {
    writeFileSync(join(path, "Cargo.toml"), `[package]\nname = "${name}"\nversion = "0.1.0"\n`);
    writeFileSync(join(path, "Cargo.lock"), "version = 3\n");
  } else if (kind === "python") {
    writeFileSync(join(path, "pyproject.toml"), `[project]\nname = "${name}"\n`);
  } else {
    writeFileSync(join(path, "go.mod"), `module bench/${name}\n\ngo 1.23\n`);
  }
}

/** The artifacts an ecosystem leaves behind, which is what the app is for. */
function fillProject(path, { random, kind }) {
  const heavy = random() < 0.25;
  const scale = heavy ? 8 : 1;

  if (kind === "node") {
    installModules(path, random, scale);
    if (random() < 0.4) buildDirectory(join(path, ".next"), 320 * MB * scale);
    if (random() < 0.3) buildDirectory(join(path, ".turbo"), 90 * MB * scale);
    if (random() < 0.3) buildDirectory(join(path, "dist"), 40 * MB * scale);
  } else if (kind === "rust") {
    const target = join(path, "target");
    mkdirSync(join(target, "debug"), { recursive: true });
    writeFileSync(join(target, "CACHEDIR.TAG"), "Signature: 8a477f597d28d172789f06886806bc55\n");
    sparse(join(target, "debug", "build.bin"), 1400 * MB * scale);
  } else if (kind === "python") {
    const venv = join(path, ".venv");
    mkdirSync(join(venv, "lib"), { recursive: true });
    writeFileSync(join(venv, "pyvenv.cfg"), "home = /usr/bin\nversion = 3.12.0\n");
    sparse(join(venv, "lib", "site-packages.bin"), 380 * MB * scale);
    buildDirectory(join(path, "__pycache__"), 12 * MB);
  } else {
    buildDirectory(join(path, "build"), 260 * MB * scale);
  }
}

/**
 * A `node_modules` with manifests in it.
 *
 * The duplicate report reads the top level of each one and identifies packages
 * by `name` and `version` in their own `package.json`, so a directory of empty
 * folders is invisible to it. The subset overlaps deliberately: that overlap is
 * the only thing the map's middle is made of.
 */
function installModules(path, random, scale) {
  const modules = join(path, "node_modules");
  mkdirSync(modules, { recursive: true });

  // One project in twelve links into a store instead of copying, which the
  // report has to recognise and exclude rather than count as waste.
  const linked = random() < 0.08;
  const store = join(path, ".pnpm-store");
  if (linked) mkdirSync(store, { recursive: true });

  for (const [name, version, weight] of CATALOGUE) {
    if (random() > 0.62) continue;
    const [scope, bare] = name.startsWith("@") ? name.split("/") : [null, name];
    const directory = scope ? join(modules, scope, bare) : join(modules, bare);

    if (linked) {
      const real = join(store, bare);
      mkdirSync(real, { recursive: true });
      writeFileSync(join(real, "package.json"), `${JSON.stringify({ name, version })}\n`);
      sparse(join(real, "index.js"), weight * MB);
      if (scope) mkdirSync(join(modules, scope), { recursive: true });
      try {
        symlinkSync(real, directory);
      } catch {
        // A link that cannot be made is not worth failing a fixture over.
      }
      continue;
    }

    mkdirSync(directory, { recursive: true });
    writeFileSync(join(directory, "package.json"), `${JSON.stringify({ name, version })}\n`);
    sparse(join(directory, "index.js"), weight * MB * scale);
  }
}

function buildDirectory(path, bytes) {
  mkdirSync(path, { recursive: true });
  sparse(join(path, "chunk.bin"), bytes);
}

function declareWorkspace(directory, family) {
  if (family.declare === "pnpm") {
    writeFileSync(join(directory, "pnpm-workspace.yaml"), "packages:\n  - '*'\n");
  } else if (family.declare === "cargo") {
    writeFileSync(
      join(directory, "Cargo.toml"),
      `[workspace]\nmembers = [${family.members.map((member) => `"${member}"`).join(", ")}]\n`,
    );
  } else if (family.declare === "go") {
    writeFileSync(join(directory, "go.work"), `go 1.23\n\nuse (\n${family.members.map((member) => `\t./${member}`).join("\n")}\n)\n`);
  } else if (family.declare === "npm") {
    writeFileSync(
      join(directory, "package.json"),
      `${JSON.stringify({ name: family.name, private: true, workspaces: family.members }, null, 2)}\n`,
    );
  }
}

/**
 * Repoints a finished repository at a remote that is not this disk.
 *
 * The fixture pushes to a bare repository beside it, because that is how you
 * get real ahead/behind counts with no network. But `git.rs` asks whether a
 * remote *leaves the machine*, and a path on the same disk does not — so every
 * project read as having no remote, every verdict came out `Protect`, and the
 * maintenance policy could never match a thing. The app was right and the
 * fixture was lying to it.
 *
 * Rewritten after the push, so `refs/remotes/origin/main` is already there:
 * ahead, behind and upstream all keep working offline. Only the URL is
 * cosmetic, and the URL is the whole of what "off machine" reads.
 */
function offMachine(path, name) {
  git(path, ["remote", "set-url", "origin", `git@github.com:uncached-bench/${name}.git`]);
}

function makeOrigin(origins, name) {
  const path = join(origins, `${name}.git`);
  if (!existsSync(path)) git(origins, ["init", "-q", "--bare", "--initial-branch=main", path]);
  return path;
}

/**
 * A file that reports its size and occupies almost nothing.
 *
 * `ftruncate` past the end leaves a hole, and every filesystem this app targets
 * stores holes as nothing at all. The scanner reads `metadata.len()`, so it
 * sees the whole number.
 */
function sparse(path, bytes) {
  const handle = openSync(path, "w");
  try {
    ftruncateSync(handle, Math.round(bytes));
  } finally {
    closeSync(handle);
  }
}

function commit(path, message, daysAgo) {
  const when = new Date(Date.now() - daysAgo * DAY).toISOString();
  git(path, ["commit", "-q", "--no-gpg-sign", "-m", message], {
    GIT_AUTHOR_DATE: when,
    GIT_COMMITTER_DATE: when,
  });
  // The walk reads mtimes too, for a project whose git says nothing useful.
  const stamp = new Date(Date.now() - daysAgo * DAY);
  utimesSync(path, stamp, stamp);
}

function git(cwd, args, env = {}) {
  execFileSync("git", args, {
    cwd,
    stdio: "ignore",
    env: { ...process.env, ...env, GIT_TERMINAL_PROMPT: "0" },
  });
}

function clean() {
  if (!existsSync(root)) {
    console.log(`Nothing at ${root}.`);
    return;
  }
  if (!existsSync(join(root, MARKER))) {
    fail(`${root} has no ${MARKER}. This script did not create it, and will not delete it.`);
  }
  rmSync(root, { recursive: true, force: true });
  console.log(`Removed ${root}.`);
}

function report(projects, elapsed) {
  console.log(`\n  ${projects.length} projects in ${root}`);
  console.log(`  ${FAMILIES.length} families, 1 repository checked out twice, 3 orphaned build directories`);
  console.log(`  built in ${(elapsed / 1000).toFixed(1)}s\n`);
  console.log("  Sizes are sparse: the app reports them in full, the disk holds almost none of it.");
  console.log(`  Remove with: node scripts/bench-workspace.mjs --clean\n`);
}

function parseArguments(argv) {
  const parsed = { clean: false, projects: 40, seed: 7, root: null };
  for (let at = 0; at < argv.length; at += 1) {
    const flag = argv[at];
    if (flag === "--clean") parsed.clean = true;
    else if (flag === "--projects") parsed.projects = Number(argv[++at]);
    else if (flag === "--seed") parsed.seed = Number(argv[++at]);
    else if (flag === "--root") parsed.root = argv[++at];
    else fail(`Unknown option: ${flag}`);
  }
  if (!Number.isFinite(parsed.projects) || parsed.projects < 0) fail("--projects needs a number");
  return parsed;
}

/** Seeded, so two runs make the same workspace and a bug stays reproducible. */
function seeded(seed) {
  let state = seed >>> 0 || 1;
  return () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 4294967296;
  };
}

function pick(random, options) {
  return options[Math.floor(random() * options.length)];
}

function fail(message) {
  console.error(`\n  ${message}\n`);
  process.exit(1);
}
