use crate::models::category::Category;
use crate::scanner::Scanner;
use std::path::Path;

pub struct NodeModulesScanner;

impl Scanner for NodeModulesScanner {
    fn category(&self) -> Category {
        Category::NodeModules
    }

    fn matches(&self, dir_name: &str) -> bool {
        dir_name == "node_modules"
    }

    fn confirm_context(&self, dir_path: &Path) -> bool {
        if is_nested_node_modules(dir_path) || is_tooling_node_modules(dir_path) {
            return false;
        }
        if let Some(parent) = dir_path.parent() {
            parent.join("package.json").exists()
        } else {
            true
        }
    }
}

fn is_nested_node_modules(path: &Path) -> bool {
    path.ancestors()
        .skip(1)
        .filter_map(Path::file_name)
        .any(|name| name.to_string_lossy().eq_ignore_ascii_case("node_modules"))
}

fn is_tooling_node_modules(path: &Path) -> bool {
    let parts = path
        .components()
        .map(|component| component.as_os_str().to_string_lossy().to_lowercase())
        .collect::<Vec<_>>();

    parts.windows(5).any(|window| {
        window
            == [
                "visualstudio",
                "msbuild",
                "microsoft",
                "visualstudio",
                "nodejs",
            ]
    }) || parts.windows(2).any(|window| {
        window[0] == "nvm"
            && window[1].starts_with('v')
            && window[1][1..].chars().all(|character| character.is_ascii_digit() || character == '.')
    })
}

#[cfg(test)]
mod tests {
    use super::{is_nested_node_modules, is_tooling_node_modules};
    use std::path::Path;

    #[test]
    fn rejects_nested_dependency_node_modules() {
        assert!(is_nested_node_modules(Path::new(
            r"D:\project\node_modules\npm\node_modules"
        )));
    }

    #[test]
    fn rejects_visual_studio_node_runtime() {
        assert!(is_tooling_node_modules(Path::new(
            r"D:\VisualStudio\MSBuild\Microsoft\VisualStudio\NodeJs\node_modules"
        )));
    }

    #[test]
    fn rejects_nvm_version_runtime() {
        assert!(is_tooling_node_modules(Path::new(
            r"D:\nvm\v20.9.0\node_modules"
        )));
    }

    #[test]
    fn keeps_regular_project_node_modules() {
        assert!(!is_nested_node_modules(Path::new(r"D:\project\node_modules")));
        assert!(!is_tooling_node_modules(Path::new(r"D:\project\node_modules")));
    }
}
