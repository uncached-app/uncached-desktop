use crate::models::category::Category;
use crate::scanner::Scanner;
use std::path::Path;
use uncached_core::Scanner as CoreScanner;

pub struct NodeModulesScanner;

impl CoreScanner for NodeModulesScanner {
    fn category(&self) -> uncached_core::Category {
        uncached_core::Category::NodeModules
    }

    fn matches(&self, dir_name: &str) -> bool {
        CoreScanner::matches(&uncached_core::NodeModulesScanner, dir_name)
    }

    fn confirm_context(&self, dir_path: &Path) -> bool {
        CoreScanner::confirm_context(&uncached_core::NodeModulesScanner, dir_path)
    }
}

impl Scanner for NodeModulesScanner {
    fn category(&self) -> Category {
        Category::NodeModules
    }

    fn matches(&self, dir_name: &str) -> bool {
        CoreScanner::matches(self, dir_name)
    }

    fn confirm_context(&self, dir_path: &Path) -> bool {
        CoreScanner::confirm_context(self, dir_path)
    }
}

#[cfg(test)]
mod tests {
    use super::NodeModulesScanner;
    use crate::scanner::Scanner;
    use std::path::Path;

    #[test]
    fn rejects_nested_dependency_node_modules() {
        assert!(!NodeModulesScanner
            .confirm_context(Path::new(r"D:\project\node_modules\npm\node_modules")));
    }

    #[test]
    fn rejects_visual_studio_node_runtime() {
        assert!(!NodeModulesScanner.confirm_context(Path::new(
            r"D:\VisualStudio\MSBuild\Microsoft\VisualStudio\NodeJs\node_modules"
        )));
    }

    #[test]
    fn rejects_nvm_version_runtime() {
        assert!(!NodeModulesScanner.confirm_context(Path::new(r"D:\nvm\v20.9.0\node_modules")));
    }

    #[test]
    fn keeps_regular_project_node_modules() {
        assert!(NodeModulesScanner.matches("node_modules"));
    }

    #[test]
    fn desktop_context_matches_core_for_missing_and_symlinked_package_json() {
        let root =
            std::env::temp_dir().join(format!("uncached-node-context-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("missing/node_modules")).unwrap();
        assert!(!NodeModulesScanner.confirm_context(&root.join("missing/node_modules")));

        let symlink_project = root.join("symlink");
        std::fs::create_dir_all(symlink_project.join("node_modules")).unwrap();
        let package = root.join("real-package.json");
        std::fs::write(&package, b"{}").unwrap();
        #[cfg(unix)]
        std::os::unix::fs::symlink(&package, symlink_project.join("package.json")).unwrap();
        #[cfg(windows)]
        if std::os::windows::fs::symlink_file(&package, symlink_project.join("package.json"))
            .is_err()
        {
            let _ = std::fs::remove_dir_all(&root);
            return;
        }
        assert!(!NodeModulesScanner.confirm_context(&symlink_project.join("node_modules")));

        let regular_project = root.join("regular");
        std::fs::create_dir_all(regular_project.join("node_modules")).unwrap();
        std::fs::write(regular_project.join("package.json"), b"{}").unwrap();
        assert!(NodeModulesScanner.confirm_context(&regular_project.join("node_modules")));
        let _ = std::fs::remove_dir_all(&root);
    }
}
